const ORDER = ["search", "code", "chat", "bell", "dashboard", "file", "terminal", "chart", "branch", "layers", "inbox", "settings", "play", "arrow"];

export function icon(name, size = 28) {
  const body = PATHS[name] || PATHS.circle;
  return `<svg class="ico" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export function iconSet(count = 4, size = 28) {
  return ORDER.slice(0, count).map((name) => icon(name, size)).join("");
}

export function iconAt(index, size = 28) {
  return icon(ORDER[index % ORDER.length], size);
}
